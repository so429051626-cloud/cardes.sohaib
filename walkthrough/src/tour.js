function linPos(t) {
  if (t <= P[0][0]) return [P[0][1], P[0][2]];
  for (let i = 1; i < P.length; i++) {
    if (t <= P[i][0]) {
      const a = P[i - 1], b = P[i];
      const u = (t - a[0]) / (b[0] - a[0]);
      return [a[1] + (b[1] - a[1]) * u, a[2] + (b[2] - a[2]) * u];
    }
  }
  const l = P[P.length - 1];
  return [l[1], l[2]];
}

function unwrap(keys) {
  const out = [[keys[0][0], keys[0][1]]];
  for (let i = 1; i < keys.length; i++) {
    let v = keys[i][1];
    const prev = out[i - 1][1];
    while (v - prev > 180) v -= 360;
    while (v - prev < -180) v += 360;
    out.push([keys[i][0], v]);
  }
  return out;
}

// monotone cubic Hermite (Fritsch-Carlson)
function monotone(keys) {
  const n = keys.length;
  const x = keys.map((k) => k[0]), y = keys.map((k) => k[1]);
  const d = [], m = new Array(n).fill(0);
  for (let i = 0; i < n - 1; i++) d.push((y[i + 1] - y[i]) / (x[i + 1] - x[i]));
  m[0] = d[0]; m[n - 1] = d[n - 2];
  for (let i = 1; i < n - 1; i++) m[i] = d[i - 1] * d[i] <= 0 ? 0 : (d[i - 1] + d[i]) / 2;
  for (let i = 0; i < n - 1; i++) {
    if (d[i] === 0) { m[i] = 0; m[i + 1] = 0; continue; }
    const a = m[i] / d[i], b = m[i + 1] / d[i];
    const s = a * a + b * b;
    if (s > 9) { const t = 3 / Math.sqrt(s); m[i] = t * a * d[i]; m[i + 1] = t * b * d[i]; }
  }
  return (t) => {
    if (t <= x[0]) return y[0];
    if (t >= x[n - 1]) return y[n - 1];
    let i = 0;
    while (i < n - 2 && t > x[i + 1]) i++;
    const h = x[i + 1] - x[i], u = (t - x[i]) / h;
    const h00 = 2 * u * u * u - 3 * u * u + 1, h10 = u * u * u - 2 * u * u + u, h01 = -2 * u * u * u + 3 * u * u, h11 = u * u * u - u * u;
    return h00 * y[i] + h10 * h * m[i] + h01 * y[i + 1] + h11 * h * m[i + 1];
  };
}

const yawF = monotone(unwrap(Y));
const hF = monotone(H);

export function sampleTour(t) {
  // smoothed position: triangle-weighted average over +-0.22 s
  const W = 0.22, N = 6;
  let sx = 0, sy = 0, sw = 0;
  for (let i = -N; i <= N; i++) {
    const w = 1 - Math.abs(i) / (N + 1);
    const p = linPos(Math.min(TOUR_END, Math.max(0, t + (i / N) * W)));
    sx += p[0] * w; sy += p[1] * w; sw += w;
  }
  let yaw = yawF(t) % 360;
  if (yaw < 0) yaw += 360;
  return { X: sx / sw, Y: sy / sw, yaw, H: hF(t) };
}
